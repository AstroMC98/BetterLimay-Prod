/* Structure only. Colours, hover and focus live with .nav-trigger in tokens.css:
   utilities outrank that layer, so shadcn's bg-/focus: classes would override
   the navy bar, and its focus:outline-none would hide the site focus ring. */
export const navigationMenuTriggerStyle = cva(
  "group inline-flex w-max items-center justify-center disabled:pointer-events-none disabled:opacity-50",
);

export const NavigationMenuTrigger = React.forwardRef<
  React.ElementRef<typeof NavigationMenuPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof NavigationMenuPrimitive.Trigger>
>(({ className, children, ...props }, ref) => (
  <NavigationMenuPrimitive.Trigger
    ref={ref}
    className={cn(navigationMenuTriggerStyle(), "group", className)}
    {...props}
  >
    {children}{" "}
    <ChevronDown
      className="relative top-px ml-1 size-3 transition duration-300 group-data-[state=open]:rotate-180 motion-reduce:transition-none"
      aria-hidden="true"
    />
  </NavigationMenuPrimitive.Trigger>
));
NavigationMenuTrigger.displayName = NavigationMenuPrimitive.Trigger.displayName;

